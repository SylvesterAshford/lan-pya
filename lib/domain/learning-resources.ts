/**
 * Resources for each topic on a stage, in the stage's topic order (left list,
 * then right list), or null when this stage has none or its topic count no
 * longer matches. Topics are matched by position because the Burmese
 * catalogue renames them; a count that disagrees means the catalogue moved
 * and the links could sit under the wrong topic, so nothing is shown.
 */
export function getStageResources(stageKey: string, topicCount: number): LearningResource[][] | null {
  const topics = LEARNING_RESOURCES[stageKey];
  if (!topics || topics.length !== topicCount) return null;
  return topics.map((topic) => topic.resources);
}

export type StageResources = Record<string, LearningResource[][] | null>;

/**
 * Resources for the stages of one path, keyed by stage key. Built on the
 * server and handed to the roadmap so the browser receives one path's links,
 * not the whole catalogue.
 */
export function resourcesForStages(stages: { key: string; left?: string[]; right?: string[] }[]): StageResources {
  return Object.fromEntries(
    stages.map((stage) => [stage.key, getStageResources(stage.key, (stage.left?.length ?? 0) + (stage.right?.length ?? 0))]),
  );
}
