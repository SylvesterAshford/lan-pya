/**
 * Free learning resources for every roadmap topic.
 *
 * Each topic on a stage (the chips beside it on the roadmap) gets something to
 * watch and something to read, chosen per topic rather than per field: Kevin
 * Powell for CSS layout, javascript.info for JavaScript, StatQuest for
 * statistics, StudioBinder for editing craft, MDN, web.dev and each tool's own
 * docs for reference. Where a good lesson taught in Burmese exists it sits
 * beside the English ones with `lang: "my"`, and a Burmese reader sees it
 * first.
 *
 * Every link was checked when it was added: videos through YouTube's oEmbed
 * endpoint (public, embeddable, from the channel named in `source`, running
 * about as long as `minutes`) and pages by loading them. `npm run
 * check:resources` re-checks them all; the last full run was 2026-10-14.
 *
 * Keyed by stage key, in the same order as the stage's topics in
 * lib/domain/career-tracks.ts (left list, then right list). The topic name is
 * kept beside each entry so a reviewer can read what a link is for;
 * tests/learning-resources.test.ts holds the two lists together.
 */

export type ResourceKind = "video" | "course" | "docs" | "article";

export type LearningResource = {
  title: string;
  url: string;
  source: string;
  kind: ResourceKind;
  /** Language of the resource itself. */
  lang: "en" | "my";
  /** Running time, for videos and courses. */
  minutes?: number;
};

export type TopicResources = { topic: string; resources: LearningResource[] };

const yt = (id: string, title: string, source: string, minutes: number, lang: "en" | "my" = "en"): LearningResource =>
  ({ title, url: `https://www.youtube.com/watch?v=${id}`, source, kind: "video", lang, minutes });
const ytList = (id: string, title: string, source: string, lang: "en" | "my" = "en"): LearningResource =>
  ({ title, url: `https://www.youtube.com/playlist?list=${id}`, source, kind: "course", lang });
const page = (url: string, title: string, source: string, kind: ResourceKind = "docs"): LearningResource =>
  ({ title, url, source, kind, lang: "en" });
const t = (topic: string, ...resources: LearningResource[]): TopicResources => ({ topic, resources });

